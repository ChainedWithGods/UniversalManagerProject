#include "ModManagerInternal.h"

#include <QDir>
#include <QFile>
#include <QFileInfo>
#include <QJsonArray>
#include <QJsonDocument>
#include <QJsonObject>

namespace {

constexpr auto kAliasesFileName = "mod_aliases.json";
constexpr auto kReadmeFileName = "MOD_ALIASES_README.txt";

constexpr auto kReadmeText = R"TXT(Universal Manager - Mod alias history
======================================

mod_aliases.json remembers every name an installed mod has used in this game
preset, keyed by the mod's internal ID. Universal Manager uses it to recognise
the mod when you re-install its original archive after renaming it, so the
existing mod is updated in place instead of creating a duplicate.

Do not edit this file by hand. Universal Manager maintains it automatically.

If you delete mod_aliases.json:
  * Your installed mods and downloads are NOT touched.
  * Renamed mods lose their history for this preset. Re-installing an archive
    whose file name no longer matches the mod's current name will install as a
    new mod, leaving the renamed one in place.
  * The file is recreated the next time you install or rename a mod, but only
    with names used from that point on.
  * Nexus update tracking is separate (nexus_updates.json) and is unaffected.

If you delete the presets folder (or this preset's folder):
  * Settings for the deleted presets are lost: game/mods paths, theme,
    favorites, tags, descriptions, mod IDs and this alias history.
  * Installed mods, archives and Nexus update tracking remain on disk.
  * Universal Manager cannot restore the deleted settings or history; restore
    a backup if you have one.
  * Without the alias history, renamed mods can no longer be matched back to
    their original archive names.

Keep this file next to mod_aliases.json when copying a preset to another
machine. Copying only preset.json will lose the rename history.
)TXT";

}

QString ModManager::modAliasesStoragePath() const
{
    const int index = findPresetIndexById(m_activePresetId);
    if (index < 0)
        return {};

    QString presetName = m_gamePresets.at(index).toMap().value("name").toString();
    if (presetName.isEmpty())
        presetName = QStringLiteral("Default");

    return getPresetFolderPath(presetName) + QLatin1Char('/')
        + QLatin1String(kAliasesFileName);
}

void ModManager::loadModAliases()
{
    m_modAliases.clear();

    const QString path = modAliasesStoragePath();
    if (path.isEmpty())
        return;

    const QString legacyPath = appDataPath() + QLatin1Char('/')
        + QLatin1String(kAliasesFileName);
    const bool migrating = !QFile::exists(path) && QFile::exists(legacyPath);

    QFile file(migrating ? legacyPath : path);
    if (!file.open(QIODevice::ReadOnly))
        return;

    const QJsonObject aliases =
        QJsonDocument::fromJson(file.readAll()).object().value("aliases").toObject();
    file.close();

    for (auto it = aliases.begin(); it != aliases.end(); ++it) {
        QStringList names;
        for (const QJsonValue& value : it.value().toArray()) {
            const QString key = mmdetail::normalizedModKey(value.toString());
            if (!key.isEmpty() && !names.contains(key))
                names.append(key);
        }
        if (!names.isEmpty())
            m_modAliases.insert(it.key(), names);
    }

    if (migrating) {
        saveModAliases();
        const QString migratedPath = legacyPath + QStringLiteral(".migrated");
        QFile::remove(migratedPath);
        if (!QFile::rename(legacyPath, migratedPath))
            QFile::remove(legacyPath);
    }
}

void ModManager::saveModAliases() const
{
    const QString path = modAliasesStoragePath();
    if (path.isEmpty())
        return;

    const QString folder = QFileInfo(path).absolutePath();
    QDir().mkpath(folder);

    QJsonObject aliases;
    for (auto it = m_modAliases.constBegin(); it != m_modAliases.constEnd(); ++it) {
        QJsonArray names;
        for (const QString& name : it.value())
            names.append(name);
        aliases.insert(it.key(), names);
    }

    QJsonObject root;
    root["version"] = 1;
    root["aliases"] = aliases;

    QFile file(path);
    if (file.open(QIODevice::WriteOnly | QIODevice::Truncate))
        file.write(QJsonDocument(root).toJson(QJsonDocument::Indented));

    QFile readme(folder + QLatin1Char('/') + QLatin1String(kReadmeFileName));
    if (readme.open(QIODevice::WriteOnly | QIODevice::Truncate))
        readme.write(kReadmeText);
}

void ModManager::copyModAliases(const QString& fromPresetName, const QString& toPresetName) const
{
    const QString sourceFolder = getPresetFolderPath(
        fromPresetName.isEmpty() ? QStringLiteral("Default") : fromPresetName);
    const QString targetFolder = getPresetFolderPath(toPresetName);
    QDir().mkpath(targetFolder);

    for (const char* fileName : {kAliasesFileName, kReadmeFileName}) {
        const QString source = sourceFolder + QLatin1Char('/') + QLatin1String(fileName);
        if (!QFile::exists(source))
            continue;
        const QString target = targetFolder + QLatin1Char('/') + QLatin1String(fileName);
        QFile::remove(target);
        QFile::copy(source, target);
    }
}

void ModManager::pruneModAliases(const QSet<QString>& knownIds)
{
    QStringList staleIds;
    for (auto it = m_modAliases.constBegin(); it != m_modAliases.constEnd(); ++it) {
        if (!knownIds.contains(it.key()))
            staleIds.append(it.key());
    }
    if (staleIds.isEmpty())
        return;

    for (const QString& id : staleIds)
        m_modAliases.remove(id);
    saveModAliases();
}

void ModManager::mergeModAliases(const QMap<QString, QStringList>& aliases)
{
    bool changed = false;
    for (auto it = aliases.constBegin(); it != aliases.constEnd(); ++it) {
        const QString uniqueId = it.key();
        if (uniqueId.isEmpty())
            continue;

        QStringList existing = m_modAliases.value(uniqueId);
        for (const QString& name : it.value()) {
            const QString key = mmdetail::normalizedModKey(name);
            if (!key.isEmpty() && !existing.contains(key)) {
                existing.append(key);
                changed = true;
            }
        }
        if (!existing.isEmpty())
            m_modAliases.insert(uniqueId, existing);
    }

    if (changed)
        saveModAliases();
}

void ModManager::forgetModAliases(const QString& uniqueId)
{
    if (!uniqueId.isEmpty() && m_modAliases.remove(uniqueId) > 0)
        saveModAliases();
}

QMap<QString, QString> ModManager::modInstallTargets() const
{
    QMap<QString, QString> targets;

    for (auto it = m_modAliases.constBegin(); it != m_modAliases.constEnd(); ++it) {
        QString currentName;
        for (auto nameIt = m_modIds.constBegin(); nameIt != m_modIds.constEnd(); ++nameIt) {
            if (nameIt.value() == it.key()) {
                currentName = nameIt.key();
                break;
            }
        }
        if (currentName.isEmpty())
            continue;

        for (const QString& alias : it.value())
            targets.insert(alias, currentName);
    }

    for (auto it = m_modIds.constBegin(); it != m_modIds.constEnd(); ++it) {
        const QString key = mmdetail::normalizedModKey(it.key());
        if (!key.isEmpty())
            targets.insert(key, it.key());
    }

    return targets;
}
